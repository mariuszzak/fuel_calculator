defmodule FuelCalculatorWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :fuel_calculator

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_fuel_calculator_key",
    signing_salt: "hf+gevEm",
    same_site: "Lax",
    # Only over HTTPS in production (config/prod.exs).
    secure:
      Application.compile_env(
        :fuel_calculator,
        [__MODULE__, :secure_session_cookie],
        false
      )
  ]

  # A mission's form is a few hundred bytes; cap WebSocket frames well above
  # that so a single huge message can't make the server hold or render megabytes.
  @max_frame_size 64_000

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options], max_frame_size: @max_frame_size],
    # No long-polling fallback: its request bodies aren't covered by
    # max_frame_size, and every browser we target has WebSockets.
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :fuel_calculator,
    gzip: not code_reloading?,
    only: FuelCalculatorWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug :ignore_devtools_probe
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug FuelCalculatorWeb.Router

  # Chrome DevTools asks every localhost page for this file (for its workspace
  # feature). We don't offer it; answer with an empty 404 before the router so
  # dev logs don't fill with NoRouteError traces. Dev only (code reloading).
  @devtools_probe [".well-known", "appspecific", "com.chrome.devtools.json"]

  defp ignore_devtools_probe(%Plug.Conn{path_info: @devtools_probe} = conn, _opts),
    do: conn |> Plug.Conn.send_resp(404, "") |> Plug.Conn.halt()

  defp ignore_devtools_probe(conn, _opts), do: conn
end
