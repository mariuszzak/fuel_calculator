defmodule FuelCalculator.MissionParams do
  # Internal to the domain: the web layer goes through the `FuelCalculator` context.
  @moduledoc false

  # Raw mission input, as submitted by the form. Every value here is untrusted:
  # it is validated and only then turned into domain structs. Planet and action
  # strings map to atoms through `Ecto.Enum`, which only accepts known values.

  use Ecto.Schema

  import Ecto.Changeset

  alias FuelCalculator.Error.FieldError
  alias FuelCalculator.Error.InvalidMission
  alias FuelCalculator.FlightStep
  alias FuelCalculator.Mission
  alias FuelCalculator.Planet

  defmodule StepParams do
    @moduledoc false

    use Ecto.Schema

    import Ecto.Changeset

    @primary_key false
    embedded_schema do
      # Generated by us when a step is added; keeps DOM rows stable when steps move.
      field(:id, :string)
      field(:action, Ecto.Enum, values: FlightStep.actions())
      field(:planet, Ecto.Enum, values: Planet.ids())
    end

    @spec changeset(%__MODULE__{}, map()) :: Ecto.Changeset.t()
    def changeset(%__MODULE__{} = step, attrs) do
      step
      # Ids are always present and well formed: RawParams guarantees it. A
      # missing or unknown action or planet becomes :unknown_action /
      # :unknown_planet when the errors are collected.
      |> cast(attrs, [:id, :action, :planet])
      |> validate_required([:action, :planet])
    end
  end

  @max_steps 20
  @min_mass_kg 1
  @max_mass_kg 1_000_000_000
  # Longer digit strings are out of range; checked before converting to an integer.
  @max_mass_digits @max_mass_kg |> Integer.digits() |> length()
  # Far beyond any valid mass ("1,000,000,000" is 13 characters), short enough to
  # parse and render cheaply; RawParams keeps one character more, so a longer
  # value is rejected instead of being cut into a different, valid number.
  @max_mass_length 32

  @primary_key false
  embedded_schema do
    field(:mass, :string)
    embeds_many(:steps, StepParams, on_replace: :delete)
  end

  @doc false
  @spec min_mass_kg() :: 1
  def min_mass_kg, do: @min_mass_kg

  @doc false
  @spec max_mass_kg() :: 1_000_000_000
  def max_mass_kg, do: @max_mass_kg

  @doc false
  @spec max_mass_length() :: 32
  def max_mass_length, do: @max_mass_length

  @doc false
  @spec step_limit() :: 20
  def step_limit, do: @max_steps

  @doc false
  # Whether a path of this many steps is within the limit.
  @spec fits?(non_neg_integer()) :: boolean()
  def fits?(step_count) when is_integer(step_count) and step_count >= 0,
    do: step_count <= @max_steps

  @spec changeset(map()) :: Ecto.Changeset.t()
  def changeset(attrs) when is_map(attrs) do
    %__MODULE__{}
    |> cast(attrs, [:mass])
    |> validate_mass()
    |> cast_steps(attrs)
    # The form shows field errors only for a changeset with an action.
    |> then(&%{&1 | action: :validate})
  end

  @spec to_mission(Ecto.Changeset.t()) :: {:ok, Mission.t()} | {:error, InvalidMission.t()}
  def to_mission(%Ecto.Changeset{} = changeset) do
    case apply_action(changeset, :validate) do
      {:ok, %__MODULE__{mass: mass, steps: steps}} ->
        {:ok, mass_kg} = parse_mass(mass)
        {:ok, Mission.new!(mass_kg, Enum.map(steps, &to_flight_step/1))}

      {:error, %Ecto.Changeset{} = invalid} ->
        {:error, invalid_mission(invalid)}
    end
  end

  @doc false
  # Every submitted step in order, with its id: the validated step, or nil while
  # the step's own input is invalid.
  @spec submitted_steps(Ecto.Changeset.t()) :: [{String.t(), FlightStep.t() | nil}]
  def submitted_steps(%Ecto.Changeset{} = changeset) do
    changeset
    |> get_embed(:steps, :changeset)
    |> Enum.map(fn
      %Ecto.Changeset{valid?: true} = step ->
        %StepParams{id: id} = step_params = apply_changes(step)
        {id, to_flight_step(step_params)}

      %Ecto.Changeset{valid?: false} = step ->
        {get_field(step, :id), nil}
    end)
  end

  defp to_flight_step(%StepParams{action: action, planet: planet_id}) do
    FlightStep.new(action, Planet.fetch!(planet_id))
  end

  defp validate_mass(changeset) do
    case changeset |> get_field(:mass) |> parse_mass() do
      {:ok, _mass_kg} ->
        changeset

      {:error, code, details} ->
        add_error(changeset, :mass, "is invalid", code: code, details: details)
    end
  end

  defp parse_mass(nil), do: {:error, :required, %{}}
  defp parse_mass(raw) when is_binary(raw), do: raw |> String.trim() |> parse_trimmed_mass()

  defp parse_trimmed_mass(""), do: parse_mass(nil)

  defp parse_trimmed_mass("-" <> _rest),
    do: {:error, :negative, %{}}

  # Plain digits, or digits grouped in threes by commas ("28,801").
  @mass_format ~r/\A(\d+|\d{1,3}(,\d{3})+)\z/

  defp parse_trimmed_mass(text) do
    cond do
      String.length(text) > @max_mass_length ->
        {:error, :too_large, %{max: @max_mass_kg}}

      not Regex.match?(@mass_format, text) ->
        {:error, :not_whole_kg, %{}}

      significant_digits(text) |> byte_size() > @max_mass_digits ->
        {:error, :too_large, %{max: @max_mass_kg}}

      true ->
        text |> significant_digits() |> String.to_integer() |> check_mass_range()
    end
  end

  # Digits without separators or leading zeros ("00,028,801" -> "28801"), so the
  # length check only counts digits that carry value.
  defp significant_digits(text) do
    case text |> String.replace(",", "") |> String.trim_leading("0") do
      "" -> "0"
      digits -> digits
    end
  end

  defp check_mass_range(mass_kg) when mass_kg < @min_mass_kg,
    do: {:error, :too_small, %{min: @min_mass_kg}}

  defp check_mass_range(mass_kg) when mass_kg > @max_mass_kg,
    do: {:error, :too_large, %{max: @max_mass_kg}}

  defp check_mass_range(mass_kg), do: {:ok, mass_kg}

  # The step limit is checked on the raw params, before casting, so an oversized
  # request is rejected without processing every step.
  defp cast_steps(changeset, attrs) do
    if raw_step_count(Map.get(attrs, "steps")) > @max_steps do
      add_error(changeset, :steps, "is invalid",
        code: :too_many_steps,
        details: %{max: @max_steps}
      )
    else
      cast_embed(changeset, :steps, with: &StepParams.changeset/2)
    end
  end

  # RawParams always gives a list (possibly empty).
  defp raw_step_count(steps) when is_list(steps), do: length(steps)

  defp invalid_mission(changeset) do
    changeset
    |> traverse_errors(&error_code/3)
    |> flatten_errors([])
    |> InvalidMission.new()
  end

  # Mass and step-count errors carry their code; a step's action or planet
  # error (missing or unknown) is identified by the field.
  defp error_code(_changeset, _field, {_message, opts}) when is_list(opts) do
    case {Keyword.fetch(opts, :code), Keyword.get(opts, :details, %{})} do
      {{:ok, code}, details} -> {code, details}
      {:error, _details} -> nil
    end
  end

  defp flatten_errors(errors, path) when is_map(errors) do
    errors
    |> Enum.sort_by(fn {field, _codes} -> to_string(field) end)
    |> Enum.flat_map(fn {field, value} -> flatten_value(value, path ++ [field]) end)
  end

  # A field's value is either a list of codes or, for embeds, one error map per step.
  defp flatten_value(values, path) when is_list(values) do
    values
    |> Enum.with_index()
    |> Enum.flat_map(fn
      {{code, details}, _index} when is_atom(code) -> [FieldError.new(path, code, details)]
      {nil, _index} -> [FieldError.new(path, step_field_code(List.last(path)))]
      {nested, index} when is_map(nested) -> flatten_errors(nested, path ++ [index])
    end)
  end

  defp step_field_code(:action), do: :unknown_action
  defp step_field_code(:planet), do: :unknown_planet
end
