defmodule FuelCalculator.MissionParams do
  # Internal to the domain: the web layer goes through the `FuelCalculator` context.
  @moduledoc false

  # Raw mission input, as submitted by the form. Every value here is untrusted:
  # it is validated and only then turned into domain structs. Planet and action
  # strings map to atoms through `Ecto.Enum`, which only accepts known values.

  use Ecto.Schema

  import Ecto.Changeset

  alias FuelCalculator.Error.FieldError
  alias FuelCalculator.Error.InvalidMission
  alias FuelCalculator.FlightStep
  alias FuelCalculator.Mission
  alias FuelCalculator.Planet

  defmodule StepParams do
    @moduledoc false

    use Ecto.Schema

    import Ecto.Changeset

    @primary_key false
    embedded_schema do
      # Generated by us when a step is added; keeps DOM rows stable when steps move.
      field(:id, :string)
      field(:action, Ecto.Enum, values: FlightStep.actions())
      field(:planet, Ecto.Enum, values: Planet.ids())
    end

    @spec changeset(%__MODULE__{}, map()) :: Ecto.Changeset.t()
    def changeset(%__MODULE__{} = step, attrs) do
      step
      |> cast(attrs, [:id, :action, :planet], message: &cast_message/2)
      |> validate_required([:id])
      |> validate_required([:action], message: "Choose launch or land.")
      |> validate_required([:planet], message: "Choose Earth, Moon or Mars.")
    end

    defp cast_message(:action, _meta), do: "Choose launch or land."
    defp cast_message(:planet, _meta), do: "Choose Earth, Moon or Mars."
    defp cast_message(:id, _meta), do: "is invalid"
  end

  @max_steps 20
  @max_mass_kg 1_000_000_000
  # Longer digit strings are out of range; checked before converting to an integer.
  @max_mass_digits 10

  @primary_key false
  embedded_schema do
    field(:mass, :string)
    embeds_many(:steps, StepParams, on_replace: :delete)
  end

  @doc false
  @spec step_limit() :: 20
  def step_limit, do: @max_steps

  @doc false
  @spec room_for_another_step?(non_neg_integer()) :: boolean()
  def room_for_another_step?(step_count) when is_integer(step_count) and step_count >= 0,
    do: step_count < @max_steps

  @spec changeset(map()) :: Ecto.Changeset.t()
  def changeset(attrs) when is_map(attrs) do
    %__MODULE__{}
    |> cast(attrs, [:mass])
    |> validate_mass()
    |> cast_steps(attrs)
  end

  @spec to_mission(Ecto.Changeset.t()) :: {:ok, Mission.t()} | {:error, InvalidMission.t()}
  def to_mission(%Ecto.Changeset{} = changeset) do
    case apply_action(changeset, :validate) do
      {:ok, %__MODULE__{mass: mass, steps: steps}} ->
        {:ok, mass_kg} = parse_mass(mass)
        {:ok, Mission.new!(mass_kg, Enum.map(steps, &to_flight_step/1))}

      {:error, %Ecto.Changeset{} = invalid} ->
        {:error, invalid_mission(invalid)}
    end
  end

  @doc false
  # The steps that are valid on their own, even when the rest of the input isn't.
  @spec valid_steps(Ecto.Changeset.t()) :: [FlightStep.t()]
  def valid_steps(%Ecto.Changeset{} = changeset) do
    changeset
    |> get_embed(:steps, :changeset)
    |> Enum.filter(& &1.valid?)
    |> Enum.map(fn %Ecto.Changeset{} = step -> step |> apply_changes() |> to_flight_step() end)
  end

  @doc false
  # The submitted step ids in order, including steps that are otherwise invalid.
  @spec step_ids(Ecto.Changeset.t()) :: [String.t() | nil]
  def step_ids(%Ecto.Changeset{} = changeset) do
    changeset
    |> get_embed(:steps, :changeset)
    |> Enum.map(fn %Ecto.Changeset{} = step -> get_field(step, :id) end)
  end

  @doc false
  @spec steps_valid?(Ecto.Changeset.t()) :: boolean()
  def steps_valid?(%Ecto.Changeset{} = changeset) do
    changeset |> get_embed(:steps, :changeset) |> Enum.all?(& &1.valid?)
  end

  defp to_flight_step(%StepParams{action: action, planet: planet_id}) do
    FlightStep.new(action, Planet.fetch!(planet_id))
  end

  defp validate_mass(changeset) do
    case changeset |> get_field(:mass) |> parse_mass() do
      {:ok, _mass_kg} -> changeset
      {:error, message} -> add_error(changeset, :mass, message)
    end
  end

  defp parse_mass(nil), do: {:error, "Enter the spacecraft mass in kilograms."}
  defp parse_mass(raw) when is_binary(raw), do: raw |> String.trim() |> parse_trimmed_mass()

  defp parse_trimmed_mass(""), do: parse_mass(nil)

  defp parse_trimmed_mass("-" <> _rest),
    do: {:error, "Mass must be a positive number of kilograms."}

  defp parse_trimmed_mass(text) do
    cond do
      not Regex.match?(~r/\A\d+\z/, text) ->
        {:error, "Use whole kilograms, digits only, for example 28801."}

      byte_size(text) > @max_mass_digits ->
        {:error, "Mass must be at most 1,000,000,000 kg."}

      true ->
        text |> String.to_integer() |> check_mass_range()
    end
  end

  defp check_mass_range(mass_kg) when mass_kg < 1, do: {:error, "Mass must be at least 1 kg."}

  defp check_mass_range(mass_kg) when mass_kg > @max_mass_kg,
    do: {:error, "Mass must be at most 1,000,000,000 kg."}

  defp check_mass_range(mass_kg), do: {:ok, mass_kg}

  # The step limit is checked on the raw params, before casting, so an oversized
  # request is rejected without processing every step.
  defp cast_steps(changeset, attrs) do
    if raw_step_count(Map.get(attrs, "steps")) > @max_steps do
      add_error(changeset, :steps, "A flight path holds up to #{@max_steps} steps.")
    else
      cast_embed(changeset, :steps, with: &StepParams.changeset/2)
    end
  end

  defp raw_step_count(steps) when is_map(steps), do: map_size(steps)
  defp raw_step_count(steps) when is_list(steps), do: length(steps)
  defp raw_step_count(_not_a_collection), do: 0

  defp invalid_mission(changeset) do
    changeset
    # Our messages have no %{placeholders} to interpolate.
    |> traverse_errors(fn {message, _opts} -> message end)
    |> flatten_errors([])
    |> InvalidMission.new()
  end

  defp flatten_errors(errors, path) when is_map(errors) do
    errors
    |> Enum.sort_by(fn {field, _messages} -> to_string(field) end)
    |> Enum.flat_map(fn {field, value} -> flatten_value(value, path ++ [field]) end)
  end

  # A field's value is either a list of messages or, for embeds, one error map per step.
  defp flatten_value(values, path) when is_list(values) do
    values
    |> Enum.with_index()
    |> Enum.flat_map(fn
      {message, _index} when is_binary(message) -> [FieldError.new(path, message)]
      {nested, index} when is_map(nested) -> flatten_errors(nested, path ++ [index])
    end)
  end
end
