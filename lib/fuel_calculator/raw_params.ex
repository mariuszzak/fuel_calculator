defmodule FuelCalculator.RawParams do
  # Internal to the domain: the web layer goes through the `FuelCalculator` context.
  @moduledoc false

  # The one reader of mission params from the browser. Validation, step editing
  # and the LiveView's stored state all work on what `normalize/1` returns, so
  # untrusted input is bounded once, in one place:
  #
  #   * only the "mass" and "steps" keys are kept;
  #   * the mass is a trimmed string of bounded length (or nil);
  #   * steps are a list of maps with string "id", "action" and "planet";
  #     non-map entries are dropped, values are bounded, and every id is a
  #     well-formed, unique string (missing or bad ids get a fresh one);
  #   * at most one step over the limit is kept, so the limit can still be
  #     reported without processing a huge payload.

  alias FuelCalculator.MissionParams

  @type t :: %{required(String.t()) => String.t() | nil | [%{required(String.t()) => String.t()}]}

  # Action and planet names are short words; anything longer is invalid anyway.
  @max_value_length 16
  # Step ids are generated by us (UUIDs); accept that shape and similar short ids.
  @id_format ~r/\A[0-9A-Za-z_-]{1,64}\z/
  # Form submissions index steps as "0", "1", ...; three digits cover any valid path.
  @index_format ~r/\A\d{1,3}\z/

  @spec normalize(map()) :: t()
  def normalize(params) when is_map(params) do
    %{"mass" => mass(Map.get(params, "mass")), "steps" => steps(Map.get(params, "steps"))}
  end

  # Trimmed first, then kept to one character over the limit: enough for
  # MissionParams to reject it, never cut down into a different valid number.
  defp mass(value) when is_binary(value),
    do: value |> String.trim() |> String.slice(0, MissionParams.max_mass_length() + 1)

  # Anything that isn't text (numbers, lists, maps from a tampered request).
  defp mass(_missing_or_not_text), do: nil

  defp steps(steps) do
    {steps, _seen_ids} =
      steps
      |> entries()
      |> Enum.filter(&is_map/1)
      |> Enum.take(MissionParams.step_limit() + 1)
      |> Enum.map_reduce(MapSet.new(), &step/2)

    steps
  end

  defp entries(steps) when is_list(steps), do: steps

  defp entries(steps) when is_map(steps) do
    steps
    |> Enum.filter(fn {key, _step} -> is_binary(key) and Regex.match?(@index_format, key) end)
    |> Enum.sort_by(fn {key, _step} -> String.to_integer(key) end)
    |> Enum.map(fn {_key, step} -> step end)
  end

  defp entries(_missing_or_invalid), do: []

  defp step(raw, seen_ids) do
    id = unique_id(Map.get(raw, "id"), seen_ids)

    step = %{
      "id" => id,
      "action" => short_text(Map.get(raw, "action")),
      "planet" => short_text(Map.get(raw, "planet"))
    }

    {step, MapSet.put(seen_ids, id)}
  end

  defp unique_id(id, seen_ids) when is_binary(id) do
    if Regex.match?(@id_format, id) and not MapSet.member?(seen_ids, id),
      do: id,
      else: Ecto.UUID.generate()
  end

  defp unique_id(_missing_or_not_text, _seen_ids), do: Ecto.UUID.generate()

  defp short_text(value) when is_binary(value), do: String.slice(value, 0, @max_value_length)
  defp short_text(_missing_or_not_text), do: ""
end
